#!/usr/bin/env bash
# note.sh — durable memory store for GHOST OPERATOR.
# Hard-won lessons, discarded assumptions, verified techniques, and negative evidence.
# A lesson that cannot be transferred is a story, not a reference — so --transfer is mandatory.
set -uo pipefail

BASE="$HOME/cyber-lessons"
LESSONS="$BASE/lessons"; MISTAKES="$BASE/mistakes.md"; PLAYBOOK="$BASE/playbook.md"
NEGATIVES="$BASE/negatives.md"; QUICKWINS="$BASE/quickwins.md"; INDEX="$BASE/INDEX.md"
AGENTS_MD="$HOME/AGENTS.md"
AREAS="web crypto forensics stego rev pwn osint recon ad cloud ir mal c2 tooling misc"

mkdir -p "$LESSONS" "$BASE"
ensure_header() { # ensure_header <file> <header text>
  local f="$1" hdr="$2"
  [[ -e "$f" ]] || { printf '%b' "$hdr" > "$f"; return; }
  if ! head -1 "$f" | grep -q '^# '; then printf '%b\n' "$hdr" > "$f.new"; cat "$f" >> "$f.new"; mv "$f.new" "$f"; fi
}
ensure_header "$MISTAKES"  '# Wrong-Assumption Log\n\nAppend-only. Every time an agent assumed something and was wrong, it lands here.\nFormat: `- **date** <assumption> — _correction:_ <what was actually true>`\n'
ensure_header "$PLAYBOOK"  '# Verified Technique Playbook\n\nOnly entries that were **run and confirmed**. Appended by `note.sh technique`.\n'
ensure_header "$NEGATIVES" '# Negative Evidence\n\nTechniques that did NOT apply, and why. Prevents confidently repeating a wrong approach.\nFormat: `- **date** <technique> — _did not apply because:_ <the distinguishing condition>`\n'
ensure_header "$QUICKWINS" '# Quick Wins\n\nThings that were easy in a way that was not obvious. Prevents over-engineering.\nFormat: `- **date** <what> — _do not over-engineer:_ <simpler path>`\n'

today() { date -u +%Y-%m-%d; }
now()   { date -u +%H:%M; }
die()   { printf 'note.sh: %s\n' "$1" >&2; exit 1; }
host()  { hostname 2>/dev/null || echo unknown; }

slug() { printf '%s' "$1" | tr '[:upper:]' '[:lower:]' | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//' | cut -c1-48; }
next_id() { local last; last=$(find "$LESSONS" -maxdepth 1 -name 'L*.md' -printf '%f\n' 2>/dev/null | sed -E 's/^L([0-9]+).*/\1/' | sort -n | tail -1); printf 'L%04d' "$(( ${last:-0} + 1 ))"; }
one_line() { printf '%s' "${1:-}" | tr '\n' ' ' | tr -s ' ' | sed -E 's/^ +| +$//g' | awk '{ if (length($0)<=160) print; else { s=substr($0,1,160); sub(/ [^ ]*$/,"",s); print s " ~" } }'; }
emit() { printf '%s' "${1:-}" | sed -E 's/^/    /'; }
field() { sed -nE "s/^$2: *(.*)$/\1/p" "$1" 2>/dev/null | head -1; }
valid_area() { local a; for a in $AREAS; do [[ "$a" == "$1" ]] && return 0; done; return 1; }
require_area() { AREA="${AREA:-misc}"; valid_area "$AREA" || die "--area '$AREA' is not in the taxonomy. Use one of: $AREAS"; }

AREA=""; CONTEXT=""; TRIGGER=""; WRONG=""; FIX=""; VERIFY=""; TRANSFER=""; TAGS=""; CMD=""; NOTE=""; CORRECTION=""
parse_pairs() {
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --area) AREA="${2:-}"; shift 2 ;;
      --context) CONTEXT="${2:-}"; shift 2 ;;
      --trigger) TRIGGER="${2:-}"; shift 2 ;;
      --wrong) WRONG="${2:-}"; shift 2 ;;
      --fix) FIX="${2:-}"; shift 2 ;;
      --verify) VERIFY="${2:-}"; shift 2 ;;
      --transfer) TRANSFER="${2:-}"; shift 2 ;;
      --tags) TAGS="${2:-}"; shift 2 ;;
      --cmd) CMD="${2:-}"; shift 2 ;;
      --note) NOTE="${2:-}"; shift 2 ;;
      --correction) CORRECTION="${2:-}"; shift 2 ;;
      --because) BECAUSE="${2:-}"; shift 2 ;;
      --do-not) DONOT="${2:-}"; shift 2 ;;
      --force) FORCE=1; shift ;;
      *) die "unknown flag '$1' (value: '${2:-}')" ;;
    esac
  done
}

dupcheck() {
  local newtext="$1" best="" bestscore=0 f id t
  for f in "$LESSONS"/L*.md; do
    [[ -e "$f" ]] || continue
    id=$(field "$f" id)
    t="$(field "$f" area) $(field "$f" title) $(field "$f" tags)"
    local score
    score=$(python3 - "$newtext" "$t" <<'PY' 2>/dev/null || echo 0
import sys,re
def tok(s): return {w for w in re.findall(r'[a-z0-9]+', s.lower()) if len(w)>2}
a,b=tok(sys.argv[1]),tok(sys.argv[2])
u=a|b
print(round(len(a&b)/len(u),3) if u else 0)
PY
)
    if awk "BEGIN{exit !($score > $bestscore)}"; then bestscore="$score"; best="$id"; fi
  done
  printf '%s %s' "$best" "$bestscore"
}

rebuild_index() {
  local tmp; tmp="$(mktemp)"
  {
    echo "# Memory Index"; echo
    echo "Auto-generated by \`note.sh index\`. Do not hand-edit — append via \`note.sh\`."
    echo "Last rebuilt: $(today) $(now) UTC"; echo
    echo "Read this file first. It is the map of everything hard-won so far."; echo

    echo "## Hard-won lessons"; echo
    echo "| ID | Area | Lesson | Trigger (why it was hard) |"
    echo "|----|------|--------|--------------------------|"
    local f
    while IFS= read -r f; do
      [[ -n "$f" ]] || continue
      printf '| %s | %s | %s | %s |\n' "$(field "$f" id)" "$(field "$f" area)" \
        "$(one_line "$(field "$f" title)")" "$(one_line "$(field "$f" trigger)")"
    done < <(find "$LESSONS" -maxdepth 1 -name 'L*.md' 2>/dev/null | sort)

    for spec in "Wrong-assumption log:$MISTAKES" "Negative evidence:$NEGATIVES" "Quick wins:$QUICKWINS"; do
      local title="${spec%%:*}" path="${spec#*:}"
      echo; echo "## $title"; echo
      if [[ -s "$path" ]] && grep -q '^- ' "$path" 2>/dev/null; then
        local n; n=$(grep -c '^- ' "$path")
        echo "($n entries)"; echo
        grep '^- ' "$path"
      else
        echo "_none yet_"
      fi
    done

    echo; echo "## Verified techniques"; echo
    if [[ -s "$PLAYBOOK" ]] && grep -q '^### ' "$PLAYBOOK" 2>/dev/null; then
      grep -E '^### ' "$PLAYBOOK" | sed 's/^### /- /'
    else
      echo "_none yet_"
    fi
    echo
  } > "$tmp"
  mv "$tmp" "$INDEX"
}

case "${1:-}" in
  lesson)
    [[ $# -ge 2 ]] || die "usage: note.sh lesson \"<title>\" --area ..."
    shift; TITLE="$1"; shift
    parse_pairs "$@"
    [[ -n "$TRIGGER"  ]] || die "--trigger is required: say WHY this was hard (attempts, time, discarded assumption)"
    [[ -n "$FIX"      ]] || die "--fix is required: the actual root cause or technique that worked"
    [[ -n "$TRANSFER" ]] || die "--transfer is required: when to reuse this in a DIFFERENT challenge (that is the point of a reference)"
    require_area
    if [[ -z "${FORCE:-}" ]]; then
      read -r dupid dupscore < <(dupcheck "$AREA $TITLE $TAGS")
      if [[ -n "$dupid" ]] && awk "BEGIN{exit !($dupscore > 0.45)}"; then
        die "possible duplicate of $dupid (similarity $dupscore). Use --force to log anyway, or add --supersedes $dupid"
      fi
    fi
    ID="$(next_id)"
    F="$LESSONS/$ID-$(slug "$TITLE").md"
    {
      echo "id: $ID"; echo "date: $(today)"; echo "host: $(host)"; echo "area: $AREA"
      echo "tags: $TAGS"; echo "title: $(one_line "$TITLE")"; echo "context: $(one_line "$CONTEXT")"
      echo "trigger: $(one_line "$TRIGGER")"; echo "fix: $(one_line "$FIX")"
      echo "verify: $(one_line "$VERIFY")"; echo "transfer: $(one_line "$TRANSFER")"
      echo "---"; echo
      echo "## Trigger — why this was hard"; emit "$TRIGGER"; echo
      echo "## Wrong assumptions discarded"
      if [[ -n "$WRONG" ]]; then emit "$WRONG"; else echo "    (none recorded)"; fi; echo
      echo "## Actual root cause / what worked"; emit "$FIX"; echo
      echo "## Verification (the command that proves it)"
      if [[ -n "$VERIFY" ]]; then emit "$VERIFY"; else echo "    (TODO)"; fi; echo
      echo "## Transfer — reuse this when"; emit "$TRANSFER"; echo
      [[ -n "${BECAUSE:-}" ]] && { echo "## Did NOT apply when"; emit "$BECAUSE"; echo; }
    } > "$F"
    [[ -n "$WRONG" ]] && printf '\n- **%s** %s — _correction:_ %s\n' "$(today)" "$(one_line "$WRONG")" "$(one_line "$FIX")" >> "$MISTAKES"
    rebuild_index
    printf 'logged %s -> %s\n' "$ID" "$F"
    ;;

  mistake)
    [[ $# -ge 2 ]] || die "usage: note.sh mistake \"<assumption>\" [--area a] [--correction c]"
    shift; W="$1"; shift
    parse_pairs "$@"
    printf '\n- **%s** %s' "$(today)" "$(one_line "$W")" >> "$MISTAKES"
    [[ -n "$CONTEXT"    ]] && printf ' _(context: %s)_' "$(one_line "$CONTEXT")" >> "$MISTAKES"
    [[ -n "$CORRECTION" ]] && printf ' — _correction:_ %s' "$(one_line "$CORRECTION")" >> "$MISTAKES"
    printf '\n' >> "$MISTAKES"
    rebuild_index; printf 'logged mistake -> %s\n' "$MISTAKES"
    ;;

  technique)
    [[ $# -ge 2 ]] || die "usage: note.sh technique \"<name>\" --area a --cmd \"<verified command>\" [--note n]"
    shift; NAME="$1"; shift
    parse_pairs "$@"
    [[ -n "$CMD" ]] || die "--cmd is required: paste the command/pattern that actually worked"
    require_area
    { printf '\n### %s — %s (%s)\n\n' "$(one_line "$NAME")" "$AREA" "$(today)"
      printf '```bash\n%s\n```\n' "$CMD"; [[ -n "$NOTE" ]] && printf '\n%s\n' "$NOTE"; } >> "$PLAYBOOK"
    rebuild_index; printf 'logged technique -> %s\n' "$PLAYBOOK"
    ;;

  negative)
    [[ $# -ge 2 ]] || die "usage: note.sh negative \"<technique>\" --because \"<why it did not apply>\" [--context c]"
    shift; NEG="$1"; shift
    parse_pairs "$@"
    [[ -n "${BECAUSE:-}" ]] || die "--because is required: state the DISTINGUISHING CONDITION that made this not apply"
    printf '\n- **%s** %s' "$(today)" "$(one_line "$NEG")" >> "$NEGATIVES"
    [[ -n "$CONTEXT" ]] && printf ' _(context: %s)_' "$(one_line "$CONTEXT")" >> "$NEGATIVES"
    printf ' — _did not apply because:_ %s\n' "$(one_line "$BECAUSE")" >> "$NEGATIVES"
    rebuild_index; printf 'logged negative -> %s\n' "$NEGATIVES"
    ;;

  quick)
    [[ $# -ge 2 ]] || die "usage: note.sh quick \"<what was easy>\" --do-not \"<what not to over-engineer>\""
    shift; QW="$1"; shift
    parse_pairs "$@"
    [[ -n "${DONOT:-}" ]] || die "--do-not is required: say what you nearly over-engineered"
    printf '\n- **%s** %s — _do not over-engineer:_ %s\n' "$(today)" "$(one_line "$QW")" "$(one_line "$DONOT")" >> "$QUICKWINS"
    rebuild_index; printf 'logged quick win -> %s\n' "$QUICKWINS"
    ;;

  relevant)
    [[ $# -ge 2 ]] || die "usage: note.sh relevant \"<task description>\" [max]"
    shift; Q="$1"; shift; MAX="${1:-5}"; require_area
    localq=$(printf '%s' "$Q" | tr '[:upper:]' '[:lower:]')
    best=""; for f in "$LESSONS"/L*.md; do
      [[ -e "$f" ]] || continue
      s=0; body=$(tr '[:upper:]' '[:lower:]' < "$f")
      for w in $(printf '%s' "$localq" | tr -c 'a-z0-9' ' ' ); do
        [[ ${#w} -le 2 ]] && continue
        grep -qi -- "$w" "$f" && s=$((s+1))
      done
      [[ "$(field "$f" area)" == "$AREA" ]] && s=$((s+2))
      [[ "$s" -gt 0 ]] && best="$best$s|$f"$'\n'
    done
    if [[ -z "$best" ]]; then echo "no relevant lessons for: $Q"; exit 0; fi
    printf '%s' "$best" | sort -t'|' -k1,1nr | head -n "$MAX" | while IFS='|' read -r s f; do
      echo "== [score $s] $(field "$f" id) [$(field "$f" area)] $(field "$f" title)"
      echo "   transfer: $(field "$f" transfer)"
    done
    ;;

  brief)
    echo "== Memory brief =="
    printf 'lessons=%s negatives=%s quickwins=%s mistakes=%s techniques=%s\n' \
      "$(find "$LESSONS" -maxdepth 1 -name 'L*.md' 2>/dev/null | wc -l | tr -d ' ')" \
      "$(grep -c '^- ' "$NEGATIVES" 2>/dev/null || echo 0)" \
      "$(grep -c '^- ' "$QUICKWINS" 2>/dev/null || echo 0)" \
      "$(grep -c '^- ' "$MISTAKES" 2>/dev/null || echo 0)" \
      "$(grep -c '^### ' "$PLAYBOOK" 2>/dev/null || echo 0)"
    rebuild_index >/dev/null
    ;;

  status)
    echo "== Store status ($(today)) =="
    printf 'lessons:     %s\n' "$(find "$LESSONS" -maxdepth 1 -name 'L*.md' 2>/dev/null | wc -l | tr -d ' ')"
    printf 'last lesson: %s\n' "$(find "$LESSONS" -maxdepth 1 -name 'L*.md' -printf '%TY-%Tm-%Td\n' 2>/dev/null | sort | tail -1)"
    echo "areas with no coverage:"; covered=$(for g in "$LESSONS"/L*.md; do field "$g" area; done 2>/dev/null | sort -u)
    for a in $AREAS; do grep -qx "$a" <<<"$covered" || echo "  - $a"; done
    ;;

  synthesize)
    echo "== Synthesis =="; echo "lessons per area:"; for f in "$LESSONS"/L*.md; do [[ -e "$f" ]] && field "$f" area; done 2>/dev/null | sort | uniq -c | sort -rn
    echo; echo "top tags:"; for f in "$LESSONS"/L*.md; do [[ -e "$f" ]] && field "$f" tags; done 2>/dev/null | tr ',' '\n' | sed '/^ *$/d' | sort | uniq -c | sort -rn | head
    ;;

  recheck)
    echo "== Environment-fact recheck (referenced tools still on PATH?) =="
    missing=0; f=""; tool=""
    for f in "$LESSONS"/L*.md; do
      [[ -e "$f" ]] || continue
      tool=$(field "$f" verify | awk '{print $1}' | tr -d '`$' | head -1)
      [[ -n "$tool" && "$tool" != "-" ]] || continue
      command -v "$tool" >/dev/null 2>&1 || { echo "  MISSING tool '$tool' referenced by $(field "$f" id) ($(field "$f" title))"; missing=$((missing+1)); }
    done
    echo "  ${missing} lesson(s) reference a tool no longer on PATH. Log a note.sh lesson or negative to update."
    ;;

  check-sync)
    echo "== check-sync (WARN ONLY — never writes) =="
    [[ -r "$AGENTS_MD" ]] || { echo "  (no $AGENTS_MD)"; exit 0; }
    hits=0; f=""; tok=""
    for f in "$LESSONS"/L*.md; do
      [[ -e "$f" ]] || continue
      while IFS= read -r tok; do
        [[ ${#tok} -ge 6 ]] || continue
        case "$tok" in
          command|commands|category|categories|example|output|result|results|version|default|content|results|status|server|client|request|response|template|templates) continue ;;
        esac
        if grep -qF -- "$tok" "$AGENTS_MD" 2>/dev/null; then
          echo "  DUP: '$(field "$f" id)' and AGENTS.md both mention '$tok' — AGENTS.md owns toolchain facts; keep the lesson, drop the fact"
          hits=$((hits+1))
        fi
      done < <(field "$f" verify | tr ' ;|&' '\n\n\n\n\n' | grep -oE '/?~?[A-Za-z0-9_.-]{6,}' | sort -u)
    done
    echo "  $hits overlap(s). Nothing was modified."
    ;;

  index) rebuild_index; printf 'rebuilt %s\n' "$INDEX" ;;
  list)
    a="" g=""
    while [[ $# -gt 0 ]]; do case "$1" in
      --area) a="$2"; shift 2 ;; --grep) g="$2"; shift 2 ;; *) shift ;; esac; done
    if [[ -n "$a" ]]; then
      for f in "$LESSONS"/L*.md; do [[ "$(field "$f" area)" == "$a" ]] && printf '%s [%s] %s\n' "$(field "$f" id)" "$a" "$(field "$f" title)"; done
    elif [[ -n "$g" ]]; then
      grep -rliE -- "$g" "$LESSONS" | while read -r f; do printf '%s %s\n' "$(field "$f" id)" "$(field "$f" title)"; done
    else
      cat "$INDEX"
    fi
    ;;
  search)
    [[ $# -ge 2 ]] || die "usage: note.sh search <term>"
    shift; grep -rniE -- "$1" "$LESSONS" "$MISTAKES" "$PLAYBOOK" "$NEGATIVES" "$QUICKWINS" 2>/dev/null \
      | awk '{ n=split($0,a,":"); line=a[length(a)]; if (length(line)>200) line=substr(line,1,200) " ~"; print a[1] ":" a[2] " " line }' \
      || printf 'no match: %s\n' "$1"
    ;;
  *) sed -n '2,3p' "$0"; sed -n '/^# Subcommands/,/^$/p' "$0" | sed 's/^# \{0,1\}//'; exit 1 ;;
esac
